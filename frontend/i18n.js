  function normalizeLocale(raw) {
    const value = String(raw || "").trim().toLowerCase();
    if (value === "zh" || value.startsWith("zh-")) return "zh-CN";
    if (value === "ms" || value.startsWith("ms-")) return "ms";
    if (value === "hi" || value.startsWith("hi-")) return "hi";
    if (value === "en" || value.startsWith("en-")) return "en";
    return "";
  }

  function resolveLocale(stored, systemLanguages) {
    const saved = normalizeLocale(stored);
    if (saved) return saved;
    for (const language of systemLanguages || []) {
      const normalized = normalizeLocale(language);
      if (normalized) return normalized;
    }
    return "en";
  }

  function translate(locale, key, variables) {
    const normalized = normalizeLocale(locale) || "en";
    const template = translations[normalized][key] || translations.en[key] || key;
    return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (_, name) => String((variables || {})[name] ?? `{${name}}`));
  }

  return { supportedLocales, translations, normalizeLocale, resolveLocale, translate };
